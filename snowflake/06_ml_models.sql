USE DATABASE ELECTRONICS_MAINTENANCE;
USE SCHEMA ML;

-- ML.FORECAST: ELECTRONICS_MAINTENANCE_FORECAST
CREATE OR REPLACE SNOWFLAKE.ML.FORECAST ML.ELECTRONICS_MAINTENANCE_FORECAST(
  INPUT_DATA => SYSTEM$REFERENCE('TABLE', 'CURATED.FORECAST_INPUT'),
  SERIES_COLNAME => 'ENTITY_ID',
  TIMESTAMP_COLNAME => 'DS',
  TARGET_COLNAME => 'Y'
  
);

CREATE OR REPLACE TABLE ML.ELECTRONICS_MAINTENANCE_FORECAST_RESULTS AS
SELECT * FROM TABLE(ML.ELECTRONICS_MAINTENANCE_FORECAST!FORECAST(FORECASTING_PERIODS => 14));

-- ML.ANOMALY_DETECTION: ELECTRONICS_MAINTENANCE_ANOMALY
CREATE OR REPLACE SNOWFLAKE.ML.ANOMALY_DETECTION ML.ELECTRONICS_MAINTENANCE_ANOMALY(
  INPUT_DATA => SYSTEM$REFERENCE('TABLE', 'CURATED.TREND_ANALYTICS'),
  SERIES_COLNAME => 'ENTITY_ID',
  TIMESTAMP_COLNAME => 'DS',
  TARGET_COLNAME => 'Y',
  LABEL_COLNAME => ''
);

CREATE OR REPLACE TABLE ML.ELECTRONICS_MAINTENANCE_ANOMALY_RESULTS AS
SELECT * FROM TABLE(ML.ELECTRONICS_MAINTENANCE_ANOMALY!DETECT_ANOMALIES(INPUT_DATA => SYSTEM$REFERENCE('TABLE', 'CURATED.TREND_ANALYTICS'), SERIES_COLNAME => 'ENTITY_ID', TIMESTAMP_COLNAME => 'DS', TARGET_COLNAME => 'Y'));

